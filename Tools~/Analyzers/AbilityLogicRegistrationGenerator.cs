using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace AetherNexus.Analyzers
{
    /// <summary>
    /// Per assembly: registers every constructible <c>IAbilityLogic</c> under its id (class name without the
    /// <c>AbilityLogic</c> suffix, matching <c>AbilityLogicRegistry.IdFor</c>). Cross-assembly id clashes are caught
    /// by <c>AbilityLogicRegistry.Register</c> at startup.
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class AbilityLogicRegistrationGenerator : IIncrementalGenerator
    {
        private const string Suffix = "AbilityLogic";

        private static readonly DiagnosticDescriptor DuplicateId = new DiagnosticDescriptor(
            "AN0105",
            "Duplicate ability logic id",
            "Ability logic id '{0}' is used by more than one class in this assembly ({1}); rename one",
            "Codegen",
            DiagnosticSeverity.Error,
            isEnabledByDefault: true);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterSourceOutput(context.CompilationProvider, Execute);
        }

        private static void Execute(SourceProductionContext context, Compilation compilation)
        {
            INamedTypeSymbol logic = compilation.GetTypeByMetadataName("GameplayAbilitySystem.IAbilityLogic");
            if (logic == null)
                return;

            var byId = new SortedDictionary<string, List<INamedTypeSymbol>>(System.StringComparer.Ordinal);
            foreach (INamedTypeSymbol type in GeneratorUtil.AllTypes(compilation.Assembly.GlobalNamespace))
            {
                if (!GeneratorUtil.IsConstructible(type) || !GeneratorUtil.Implements(type, logic) || !GeneratorUtil.IsReachableFromOwnAssembly(type))
                    continue;
                string id = IdFor(type.Name);
                if (!byId.TryGetValue(id, out var list))
                    byId[id] = list = new List<INamedTypeSymbol>();
                list.Add(type);
            }
            if (byId.Count == 0)
                return;

            var sb = new StringBuilder();
            sb.Append("// <auto-generated/> AetherNexus.Analyzers.AbilityLogicRegistrationGenerator\n");
            sb.Append("namespace GameplayAbilitySystem.Generated\n{\n");
            sb.Append("\tinternal static class AbilityLogicRegistration\n\t{\n");
            sb.Append("\t\t[global::UnityEngine.RuntimeInitializeOnLoadMethod(global::UnityEngine.RuntimeInitializeLoadType.BeforeSceneLoad)]\n");
            sb.Append("\t\tprivate static void Register()\n\t\t{\n");
            foreach (var pair in byId)
            {
                if (pair.Value.Count > 1)
                {
                    context.ReportDiagnostic(Diagnostic.Create(DuplicateId, pair.Value[1].Locations.FirstOrDefault(),
                        pair.Key, string.Join(", ", pair.Value.Select(t => t.ToDisplayString()))));
                    continue;
                }
                sb.Append("\t\t\tglobal::GameplayAbilitySystem.AbilityLogicRegistry.Register(\"").Append(pair.Key)
                  .Append("\", () => new ").Append(GeneratorUtil.CodeName(pair.Value[0])).Append("());\n");
            }
            sb.Append("\t\t}\n\t}\n}\n");
            context.AddSource("AbilityLogicRegistration.g.cs", sb.ToString());
        }

        private static string IdFor(string name)
        {
            return name.EndsWith(Suffix, System.StringComparison.Ordinal) && name.Length > Suffix.Length
                ? name.Substring(0, name.Length - Suffix.Length)
                : name;
        }
    }
}
