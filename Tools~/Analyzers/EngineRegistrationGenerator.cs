using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace AetherNexus.Analyzers
{
    /// <summary>
    /// Per assembly: direct constructor calls for every concrete engine/scene subsystem into
    /// <c>SubsystemFactoryRegistry</c> and every network backend factory into <c>NetworkBackendRegistry</c>.
    /// The direct <c>new T()</c> is what keeps each type alive under IL2CPP stripping.
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class EngineRegistrationGenerator : IIncrementalGenerator
    {
        private static readonly DiagnosticDescriptor Unreachable = new DiagnosticDescriptor(
            "AN0102",
            "Registered type is not reachable",
            "'{0}' is nested private or protected, so generated registration code in its own assembly cannot construct it; make it public or internal",
            "Codegen",
            DiagnosticSeverity.Error,
            isEnabledByDefault: true);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterSourceOutput(context.CompilationProvider, Execute);
        }

        private static void Execute(SourceProductionContext context, Compilation compilation)
        {
            INamedTypeSymbol engine = compilation.GetTypeByMetadataName("AetherNexus.GameEngineCore.Runtime.EngineSubsystem");
            INamedTypeSymbol scene = compilation.GetTypeByMetadataName("AetherNexus.GameEngineCore.Runtime.SceneSubsystem");
            INamedTypeSymbol order = compilation.GetTypeByMetadataName("AetherNexus.GameEngineCore.Runtime.SubsystemInitOrderAttribute");
            INamedTypeSymbol backend = compilation.GetTypeByMetadataName("AetherNexus.GameEngineCore.Network.INetworkBackendFactory");
            if (engine == null || scene == null || backend == null)
                return;

            var lines = new List<string>();
            foreach (INamedTypeSymbol type in GeneratorUtil.AllTypes(compilation.Assembly.GlobalNamespace))
            {
                if (!GeneratorUtil.IsConstructible(type))
                    continue;

                bool isSubsystem = GeneratorUtil.DerivesFrom(type, engine) || GeneratorUtil.DerivesFrom(type, scene);
                bool isBackend = GeneratorUtil.Implements(type, backend);
                if (!isSubsystem && !isBackend)
                    continue;

                if (!GeneratorUtil.IsReachableFromOwnAssembly(type))
                {
                    context.ReportDiagnostic(Diagnostic.Create(Unreachable, type.Locations.FirstOrDefault(), type.ToDisplayString()));
                    continue;
                }

                string name = GeneratorUtil.CodeName(type);
                if (isSubsystem)
                {
                    string initOrder = "int.MaxValue";
                    AttributeData attribute = order == null ? null : GeneratorUtil.FindAttribute(type, order, inherit: true);
                    if (attribute != null && attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Value is int value)
                        initOrder = value.ToString(System.Globalization.CultureInfo.InvariantCulture);
                    lines.Add($"global::AetherNexus.GameEngineCore.Runtime.SubsystemFactoryRegistry.Register(() => new {name}(), {initOrder});");
                }
                if (isBackend)
                    lines.Add($"global::AetherNexus.GameEngineCore.Network.NetworkBackendRegistry.Register(new {name}());");
            }

            if (lines.Count == 0)
                return;
            lines.Sort(System.StringComparer.Ordinal);

            var sb = new StringBuilder();
            sb.Append("// <auto-generated/> AetherNexus.Analyzers.EngineRegistrationGenerator\n");
            sb.Append("namespace AetherNexus.GameEngineCore.Generated\n{\n");
            sb.Append("\tinternal static class EngineRegistration\n\t{\n");
            sb.Append("#if UNITY_EDITOR\n\t\t[global::UnityEditor.InitializeOnLoadMethod]\n#endif\n");
            sb.Append("\t\t[global::UnityEngine.RuntimeInitializeOnLoadMethod(global::UnityEngine.RuntimeInitializeLoadType.BeforeSceneLoad)]\n");
            sb.Append("\t\tprivate static void Register()\n\t\t{\n");
            foreach (string line in lines)
                sb.Append("\t\t\t").Append(line).Append('\n');
            sb.Append("\t\t}\n\t}\n}\n");
            context.AddSource("EngineRegistration.g.cs", sb.ToString());
        }
    }
}
