using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace AetherNexus.Analyzers
{
    /// <summary>
    /// For each source <c>partial</c> subclass of <c>GameStateFacadeBase&lt;T&gt;</c> that does not write
    /// <c>RegisterContributors</c> itself: an override registering every <c>[StateContributorAutoRegister]</c> type
    /// visible to the assembly (its own and every referenced assembly) through its <c>public static Instance</c>.
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class StateContributorGenerator : IIncrementalGenerator
    {
        private static readonly DiagnosticDescriptor NoInstance = new DiagnosticDescriptor(
            "AN0103",
            "State contributor cannot be auto-registered",
            "'{0}' is marked [StateContributorAutoRegister] but has no accessible 'public static {0} Instance' field or property; it is not registered",
            "Codegen",
            DiagnosticSeverity.Warning,
            isEnabledByDefault: true);

        private static readonly DiagnosticDescriptor NotPartial = new DiagnosticDescriptor(
            "AN0106",
            "Game state facade must be partial",
            "'{0}' derives from GameStateFacadeBase; declare it partial so its contributor registration can be generated, or override RegisterContributors by hand",
            "Codegen",
            DiagnosticSeverity.Warning,
            isEnabledByDefault: true);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterSourceOutput(context.CompilationProvider, Execute);
        }

        private static void Execute(SourceProductionContext context, Compilation compilation)
        {
            INamedTypeSymbol facade = compilation.GetTypeByMetadataName("AetherNexus.GameEngineCore.GameState.GameStateFacadeBase`1");
            INamedTypeSymbol autoRegister = compilation.GetTypeByMetadataName("AetherNexus.GameEngineCore.Snapshot.StateContributorAutoRegisterAttribute");
            if (facade == null || autoRegister == null)
                return;

            var facades = GeneratorUtil.AllTypes(compilation.Assembly.GlobalNamespace)
                .Where(t => t.TypeKind == TypeKind.Class && !t.IsAbstract && GeneratorUtil.DerivesFrom(t, facade))
                .Where(t => !t.GetMembers("RegisterContributors").Any(m => !m.IsImplicitlyDeclared))
                .ToList();
            if (facades.Count == 0)
                return;

            var contributors = new List<INamedTypeSymbol>();
            var assemblies = new List<IAssemblySymbol> { compilation.Assembly };
            assemblies.AddRange(compilation.SourceModule.ReferencedAssemblySymbols.Where(a => !IsPlatformAssembly(a.Name)));
            foreach (IAssemblySymbol assembly in assemblies)
            {
                foreach (INamedTypeSymbol type in GeneratorUtil.AllTypes(assembly.GlobalNamespace))
                {
                    if (type.IsAbstract || GeneratorUtil.FindAttribute(type, autoRegister, inherit: false) == null)
                        continue;
                    if (!HasAccessibleInstance(type, compilation))
                    {
                        context.ReportDiagnostic(Diagnostic.Create(NoInstance, type.Locations.FirstOrDefault(l => l.IsInSource), type.ToDisplayString()));
                        continue;
                    }
                    contributors.Add(type);
                }
            }
            contributors.Sort((a, b) => string.CompareOrdinal(a.ToDisplayString(), b.ToDisplayString()));

            foreach (INamedTypeSymbol type in facades)
            {
                if (type.ContainingType != null || !type.DeclaringSyntaxReferences.All(IsPartial))
                {
                    context.ReportDiagnostic(Diagnostic.Create(NotPartial, type.Locations.FirstOrDefault(), type.ToDisplayString()));
                    continue;
                }

                var sb = new StringBuilder();
                sb.Append("// <auto-generated/> AetherNexus.Analyzers.StateContributorGenerator\n");
                bool hasNamespace = !type.ContainingNamespace.IsGlobalNamespace;
                if (hasNamespace)
                    sb.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).Append("\n{\n");
                sb.Append("\tpartial class ").Append(type.Name).Append("\n\t{\n");
                sb.Append("\t\tprotected override void RegisterContributors()\n\t\t{\n");
                foreach (INamedTypeSymbol contributor in contributors)
                    sb.Append("\t\t\tSnapshots.RegisterContributor(").Append(GeneratorUtil.CodeName(contributor)).Append(".Instance);\n");
                sb.Append("\t\t}\n\t}\n");
                if (hasNamespace)
                    sb.Append("}\n");
                context.AddSource(type.Name + ".Contributors.g.cs", sb.ToString());
            }
        }

        private static bool IsPartial(SyntaxReference reference)
        {
            return reference.GetSyntax() is Microsoft.CodeAnalysis.CSharp.Syntax.ClassDeclarationSyntax c
                   && c.Modifiers.Any(m => m.ValueText == "partial");
        }

        private static bool HasAccessibleInstance(INamedTypeSymbol type, Compilation compilation)
        {
            if (!compilation.IsSymbolAccessibleWithin(type, compilation.Assembly))
                return false;
            foreach (ISymbol member in type.GetMembers("Instance"))
            {
                if (!member.IsStatic || member.DeclaredAccessibility != Accessibility.Public)
                    continue;
                ITypeSymbol memberType = member switch
                {
                    IFieldSymbol f => f.Type,
                    IPropertySymbol p => p.Type,
                    _ => null,
                };
                if (SymbolEqualityComparer.Default.Equals(memberType, type))
                    return true;
            }
            return false;
        }

        private static bool IsPlatformAssembly(string name)
        {
            return name == "mscorlib" || name == "netstandard"
                   || name.StartsWith("System", System.StringComparison.Ordinal)
                   || name.StartsWith("Microsoft.", System.StringComparison.Ordinal)
                   || name.StartsWith("UnityEngine", System.StringComparison.Ordinal)
                   || name.StartsWith("UnityEditor", System.StringComparison.Ordinal)
                   || name.StartsWith("Unity.", System.StringComparison.Ordinal);
        }
    }
}
