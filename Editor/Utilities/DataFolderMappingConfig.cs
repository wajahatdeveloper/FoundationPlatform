    internal static class DataFolderMappingPathUtility
    {
        public static bool IsPathUnderAnyFolder(string assetPath, IReadOnlyList<string> folders)
        {
            if (folders == null || folders.Count == 0)
                return false;

            for (int i = 0; i < folders.Count; i++)
            {
                if (IsPathUnderFolder(assetPath, folders[i]))
                    return true;
            }

            return false;
        }

        public static bool IsPathUnderFolder(string assetPath, string folderPath)
        {
            if (string.IsNullOrEmpty(assetPath) || string.IsNullOrEmpty(folderPath))
                return false;

            string normalizedAsset = NormalizeAssetPath(assetPath);
            string normalizedFolder = NormalizeAssetPath(folderPath).TrimEnd('/');
            return normalizedAsset.StartsWith(normalizedFolder + "/", StringComparison.OrdinalIgnoreCase)
                   || string.Equals(normalizedAsset, normalizedFolder, StringComparison.OrdinalIgnoreCase);
        }

        public static string NormalizeAssetPath(string path)
        {
            return string.IsNullOrEmpty(path) ? string.Empty : path.Replace('\\', '/');
        }
    }

    public static class DataFolderMappingExemptionResolver
    {
        public static IReadOnlyList<string> DiscoverExemptRootFolders(DataFolderMappingConfig config)
        {
            string[] markerGuids = AssetDatabase.FindAssets("t:DataFolderExemptionMarker", new[] { "Assets" });
            var roots = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            for (int i = 0; i < markerGuids.Length; i++)
            {
                string markerPath = AssetDatabase.GUIDToAssetPath(markerGuids[i]);
                if (string.IsNullOrEmpty(markerPath))
                    continue;

                string folder = System.IO.Path.GetDirectoryName(markerPath);
                if (string.IsNullOrEmpty(folder))
                    continue;

                roots.Add(DataFolderMappingPathUtility.NormalizeAssetPath(folder));
            }

            return new List<string>(roots);
        }

        /// <summary>Discovers exempt root folders with no config.</summary>
        public static IReadOnlyList<string> DiscoverExemptRootFolders() => DiscoverExemptRootFolders(null);

        public static bool IsPathUnderExemptScope(string assetPath, IReadOnlyList<string> exemptRootFolders)
        {
            if (string.IsNullOrEmpty(assetPath))
                return false;

            IReadOnlyList<string> roots = exemptRootFolders ?? DiscoverExemptRootFolders();
            return DataFolderMappingPathUtility.IsPathUnderAnyFolder(assetPath, roots);
        }

        /// <summary>Checks the path against freshly-discovered exempt root folders.</summary>
        public static bool IsPathUnderExemptScope(string assetPath) => IsPathUnderExemptScope(assetPath, null);

        private static readonly Dictionary<Type, string> s_typeScriptPathCache = new();

        public static bool TryGetTypeScriptPath(Type type, out string scriptPath)
        {
            scriptPath = null;
            if (type == null)
                return false;

            if (s_typeScriptPathCache.TryGetValue(type, out scriptPath))
            {
                return scriptPath != null;
            }

            string[] guids = AssetDatabase.FindAssets(type.Name + " t:MonoScript");
            for (int i = 0; i < guids.Length; i++)
            {
                string path = AssetDatabase.GUIDToAssetPath(guids[i]);
                MonoScript script = AssetDatabase.LoadAssetAtPath<MonoScript>(path);
                if (script == null || script.GetClass() != type)
                    continue;

                scriptPath = DataFolderMappingPathUtility.NormalizeAssetPath(path);
                s_typeScriptPathCache[type] = scriptPath;
                return true;
            }

            s_typeScriptPathCache[type] = null;
            return false;
        }

        public static bool IsTypeScriptUnderExemptScope(Type type, IReadOnlyList<string> exemptRootFolders)
        {
            return TryGetTypeScriptPath(type, out string scriptPath)
                   && IsPathUnderExemptScope(scriptPath, exemptRootFolders);
        }

        /// <summary>Checks against freshly-discovered exempt root folders.</summary>
        public static bool IsTypeScriptUnderExemptScope(Type type) => IsTypeScriptUnderExemptScope(type, null);

        public static string ToAssetsRelativePath(string path)
        {
            string normalized = DataFolderMappingPathUtility.NormalizeAssetPath(path);
            if (string.IsNullOrEmpty(normalized))
                return string.Empty;

            int index = normalized.IndexOf("Assets/", StringComparison.OrdinalIgnoreCase);
            if (index < 0)
                return normalized;

            return normalized.Substring(index);
        }
