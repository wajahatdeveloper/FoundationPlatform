    [MenuItem(MenuPaths.Rebuild.TagsLayersScenes, false, MenuPriorities.Rebuild)]
    static void RebuildTagsAndLayersClasses()
    {
        string folderPath = System.IO.Path.Combine(Application.dataPath, FOLDER_LOCATION);
        if (!Directory.Exists(folderPath))
        {
            Directory.CreateDirectory(folderPath);
        }

        bool tagsChanged = EditorCodegen.WriteIfChanged(
            System.IO.Path.Combine(folderPath, TAGS_FILE_NAME + SCRIPT_EXTENSION),
            GetConstStringClassContent(TAGS_FILE_NAME, UnityEditorInternal.InternalEditorUtility.tags));
        bool layersChanged = EditorCodegen.WriteIfChanged(
            System.IO.Path.Combine(folderPath, LAYERS_FILE_NAME + SCRIPT_EXTENSION),
            GetLayerClassContent(LAYERS_FILE_NAME, UnityEditorInternal.InternalEditorUtility.layers));
        bool sortingLayersChanged = EditorCodegen.WriteIfChanged(
            System.IO.Path.Combine(folderPath, SORTING_LAYERS_FILE_NAME + SCRIPT_EXTENSION),
            GetSortingLayerClassContent(SORTING_LAYERS_FILE_NAME, SortingLayer.layers.Select(x => x.name).ToArray()));
        bool scenesChanged = EditorCodegen.WriteIfChanged(
            System.IO.Path.Combine(folderPath, SCENES_FILE_NAME + SCRIPT_EXTENSION),
            GetConstStringClassContent(SCENES_FILE_NAME, EditorBuildSettingsScenesToNameStrings(EditorBuildSettings.scenes)));

        if (tagsChanged)
        {
            AssetDatabase.ImportAsset("Assets/" + FOLDER_LOCATION + TAGS_FILE_NAME + SCRIPT_EXTENSION, ImportAssetOptions.Default);
        }
        if (layersChanged)
        {
            AssetDatabase.ImportAsset("Assets/" + FOLDER_LOCATION + LAYERS_FILE_NAME + SCRIPT_EXTENSION, ImportAssetOptions.Default);
        }
        if (sortingLayersChanged)
        {
            AssetDatabase.ImportAsset("Assets/" + FOLDER_LOCATION + SORTING_LAYERS_FILE_NAME + SCRIPT_EXTENSION, ImportAssetOptions.Default);
        }
        if (scenesChanged)
        {
            AssetDatabase.ImportAsset("Assets/" + FOLDER_LOCATION + SCENES_FILE_NAME + SCRIPT_EXTENSION, ImportAssetOptions.Default);
        }
        DebugX.Debug("Layers, Tags and Scenes Rebuild Complete");
    }

