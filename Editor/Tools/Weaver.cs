    private static string[] EditorBuildSettingsScenesToNameStrings(EditorBuildSettingsScene[] scenes)
    {
        string[] sceneNames = new string[scenes.Length];
        for (int n = 0; n < sceneNames.Length; n++)
        {
            sceneNames[n] = System.IO.Path.GetFileNameWithoutExtension(scenes[n].path);
        }

        return sceneNames;
    }

    private static string GetConstStringClassContent(string className, string[] labelsArray)
    {
        var sb = new System.Text.StringBuilder();
        sb.AppendLine("// This class is auto-generated. Do not modify. (TagsLayersScenesBuilder.cs)");
        sb.AppendLine("public static class " + SanitizeIdentifier(className));
        sb.AppendLine("{");
        foreach (string label in labelsArray)
        {
            sb.Append('\t').AppendLine(BuildConstStringVariable(label));
        }
        sb.Append("}");
        return sb.ToString();
    }

    private static string GetLayerClassContent(string className, string[] labelsArray)
    {
        var sb = new System.Text.StringBuilder();
        sb.AppendLine("// This class is auto-generated. Do not modify. (TagsLayersScenesBuilder.cs)");
        sb.AppendLine("public static class " + SanitizeIdentifier(className));
        sb.AppendLine("{");
        foreach (string label in labelsArray)
        {
            sb.Append('\t').AppendLine(BuildConstStringVariable(label));
        }
        sb.AppendLine();
        var usedIntNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (string label in labelsArray)
        {
            string name = DisambiguateIdentifier(ToUpperCaseWithUnderscores(label) + "_INT", usedIntNames);
            sb.Append('\t')
              .Append("public const int ")
              .Append(name).Append(" = ")
              .Append(LayerMask.NameToLayer(label))
              .AppendLine(";");
        }
        sb.Append("}");
        return sb.ToString();
    }

