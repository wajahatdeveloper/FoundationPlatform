    private static string DisambiguateIdentifier(string candidate, HashSet<string> used)
    {
        string result = candidate;
        int suffix = 1;
        while (!used.Add(result))
        {
            result = candidate + "_" + suffix;
            suffix++;
        }
        return result;
    }

    private static string BuildConstStringVariable(string varName)
    {
        return "public const string " + ToUpperCaseWithUnderscores(varName) + " = " + '"' + varName + '"' + ";";
    }

    private static string ToUpperCaseWithUnderscores(string input)
    {
        if (string.IsNullOrEmpty(input))
        {
            return "_";
        }

        var sb = new System.Text.StringBuilder();
        char first = input[0];
        if (!char.IsLetter(first) && first != '_')
        {
            sb.Append('_');
        }
        sb.Append(NormalizeIdentifierChar(first));

        for (int n = 1; n < input.Length; n++)
        {
            char current = input[n];
            char previous = input[n - 1];
            bool shouldInsertUnderscore = (char.IsUpper(current) || current == ' ') && !char.IsUpper(previous) && previous != '_' && previous != ' ';
            if (shouldInsertUnderscore)
            {
                sb.Append('_');
            }
            if (current != ' ')
            {
                sb.Append(NormalizeIdentifierChar(current));
            }
        }

        return sb.ToString().ToUpper();
    }

    private static char NormalizeIdentifierChar(char c)
    {
        if (char.IsLetterOrDigit(c) || c == '_')
        {
            return c;
        }
        return '_';
    }

    private static string SanitizeIdentifier(string input)
    {
        if (string.IsNullOrEmpty(input))
        {
            return "_";
        }
        var sb = new System.Text.StringBuilder();
        char first = input[0];
        if (!char.IsLetter(first) && first != '_')
        {
            sb.Append('_');
        }
        sb.Append(NormalizeIdentifierChar(first));
        for (int i = 1; i < input.Length; i++)
        {
            sb.Append(NormalizeIdentifierChar(input[i]));
        }
        return sb.ToString();
    }

    private static string GetAnimationsClassContent(string className)
    {
        var sb = new System.Text.StringBuilder();
        sb.AppendLine("// This class is auto-generated. Do not modify. (TagsLayersScenesBuilder.cs)");
        sb.AppendLine("public static class " + SanitizeIdentifier(className));
        sb.AppendLine("{");
        string[] controllerGuids = AssetDatabase.FindAssets("t:AnimatorController");
        foreach (string guid in controllerGuids)
        {
            string path = AssetDatabase.GUIDToAssetPath(guid);
            var controller = AssetDatabase.LoadAssetAtPath<AnimatorController>(path);
            if (controller == null) continue;
            string controllerClass = ToUpperCaseWithUnderscores(controller.name);
            sb.Append('\t').AppendLine("public static class " + SanitizeIdentifier(controllerClass));
            sb.AppendLine("\t{");
            sb.AppendLine("\t\tpublic static class PARAMETERS");
            sb.AppendLine("\t\t{");
            foreach (var param in controller.parameters)
            {
                sb.Append('\t').Append('\t').Append('\t').AppendLine(BuildConstStringVariable(param.name));
            }
            sb.AppendLine("\t\t}");
            var states = new HashSet<string>();
            for (int i = 0; i < controller.layers.Length; i++)
            {
                CollectStatesRecursive(controller.layers[i].stateMachine, states);
            }
            sb.AppendLine("\t\tpublic static class STATES");
            sb.AppendLine("\t\t{");
            foreach (var stateName in states)
            {
                sb.Append('\t').Append('\t').Append('\t').AppendLine(BuildConstStringVariable(stateName));
            }
            sb.AppendLine("\t\t}");
            sb.AppendLine("\t}");
        }
        sb.Append("}");
        return sb.ToString();
    }

    private static void CollectStatesRecursive(AnimatorStateMachine sm, HashSet<string> states)
    {
        foreach (var child in sm.states)
        {
            if (child.state != null)
            {
                states.Add(child.state.name);
            }
        }
        foreach (var sub in sm.stateMachines)
        {
            if (sub.stateMachine != null)
            {
                CollectStatesRecursive(sub.stateMachine, states);
            }
        }
    }

    private static string GetNavMeshAreasClassContent(string className)
    {
        var sb = new System.Text.StringBuilder();
        sb.AppendLine("// This class is auto-generated. Do not modify. (TagsLayersScenesBuilder.cs)");
        sb.AppendLine("public static class " + SanitizeIdentifier(className));
        sb.AppendLine("{");
        string[] areaNames = GetNavMeshAreaNamesSafe();
        foreach (var area in areaNames)
        {
            sb.Append('\t').AppendLine(BuildConstStringVariable(area));
        }
        sb.AppendLine();
        var usedIntNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (var area in areaNames)
        {
            string name = DisambiguateIdentifier(ToUpperCaseWithUnderscores(area) + "_INDEX", usedIntNames);
            sb.Append('\t').Append("public const int ").Append(name).Append(" = ")
              .Append(NavMesh.GetAreaFromName(area)).AppendLine(";");
        }
        sb.Append("}");
        return sb.ToString();
    }

    private static string[] GetNavMeshAreaNamesSafe()
    {
        try
        {
            return NavMesh.GetAreaNames();
        }
        catch
        {
            return new[] { "Walkable", "Not Walkable", "Jump" };
        }
    }

    private static string GetShadersClassContent(string className)
    {
        var sb = new System.Text.StringBuilder();
        sb.AppendLine("// This class is auto-generated. Do not modify. (TagsLayersScenesBuilder.cs)");
        sb.AppendLine("public static class " + SanitizeIdentifier(className));
        sb.AppendLine("{");
        string[] shaderGuids = AssetDatabase.FindAssets("t:Shader");
        var usedClassNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (string guid in shaderGuids)
        {
            string path = AssetDatabase.GUIDToAssetPath(guid);
            var shader = AssetDatabase.LoadAssetAtPath<Shader>(path);
            if (shader == null) continue;
            string baseName = ToUpperCaseWithUnderscores(shader.name.Replace('/', '_'));
            string candidate = SanitizeIdentifier(baseName);
            if (usedClassNames.Contains(candidate))
            {
                string fromPath = ToUpperCaseWithUnderscores(path.Replace('/', '_'));
                candidate = SanitizeIdentifier(fromPath);
            }
            if (usedClassNames.Contains(candidate))
            {
                candidate = candidate + "_" + guid.Substring(0, 8).ToUpperInvariant();
            }
            usedClassNames.Add(candidate);
            sb.Append('\t').AppendLine("public static class " + candidate);
            sb.AppendLine("\t{");
            sb.AppendLine("\t\tpublic static class PROPERTIES");
            sb.AppendLine("\t\t{");
            int propCount = shader.GetPropertyCount();
            for (int i = 0; i < propCount; i++)
            {
                string propName = shader.GetPropertyName(i);
                sb.Append('\t').Append('\t').Append('\t').AppendLine(BuildConstStringVariable(propName));
            }
            sb.AppendLine("\t\t}");
            sb.AppendLine("\t\tpublic static class KEYWORDS");
            sb.AppendLine("\t\t{");
            try
            {
                var localKeywords = shader.keywordSpace.keywords;
                foreach (var kw in localKeywords)
                {
                    sb.Append('\t').Append('\t').Append('\t').AppendLine(BuildConstStringVariable(kw.name));
                }
            }
            catch { }
            sb.AppendLine("\t\t}");
            sb.AppendLine("\t}");
        }
        sb.Append("}");
        return sb.ToString();
    }
